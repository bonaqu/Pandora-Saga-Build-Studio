import assert from 'node:assert/strict';

// Live UI render in Chromium, using only pinned OS and Remaked source files.
// No user builds, cloud requests or D1 mutations are involved in this smoke.
export async function runHeroBookGameNames664Smoke(browser,base){
 const context=await browser.newContext({viewport:{width:1100,height:850}});
 await context.route('**/*',route=>
  route.request().url().startsWith(base+'/')?route.continue():route.abort());
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 try{
  await page.goto(base+'/',{waitUntil:'domcontentloaded'});
  await page.locator('#startupOverlay').waitFor({state:'hidden',timeout:30000});
  const source=await page.evaluate(async()=>{
   const [skills,meta,classes,english]=await Promise.all(
    ['data/os/skills.json','data/os/meta.json',
     'data/os/classes.json','data/os/strings.en.json'].map(async path=>{
      const response=await fetch(path);
      if(!response.ok)throw Error('Missing pinned game source '+path);
      return response.json();
     }));
   window.__bookGameTermsQA={
    skills,branchLabels:meta.branchLabels,classes,
    englishSkills:english.skills,englishBranches:english.branches,
    englishClasses:english.classes
   };
   const host=document.createElement('div');
   host.id='book-source-qa';host.style.width='780px';host.style.height='620px';
   host.style.overflow='auto';document.body.appendChild(host);
   window.__bookHostQA=host;
   return {l10:skills['310004001']?.name,
    hymn:meta.branchLabels?.hymn,adept:classes.ACOLYTE?.name};
  });
  assert.deepEqual(source,{l10:'Лечение',hymn:'Песнопения',adept:'Адепт'});

  const render=async({lang,chapter})=>page.evaluate(({lang,chapter})=>{
   document.documentElement.lang=lang;
   const terms=window.__bookGameTermsQA,host=window.__bookHostQA;
   const skillRows=[
    {id:'firstAid',name:'Incorrect First Aid',nameEn:'Wrong',
     amount:50,scaledBySkill:true,available:true},
    {id:'heal',name:'Неверный автоперевод',nameEn:'Incorrect',
     amount:108,scaledBySkill:true,available:false,
     requires:'Ветвь аколита, уровень 18',requiresEn:'Acolyte class, level 18'},
    {id:'healingAura',skillId:310021001,name:'Bad generated name',nameEn:'Wrong',
     amount:200,scaledBySkill:true,available:true},
    {id:'sanctuary',skillId:310023001,name:'Wrong sanctuary',nameEn:'Wrong',
     amount:11,scaledBySkill:false,available:true},
    {id:'restoration',skillId:310022001,name:'Wrong restoration',nameEn:'Wrong',
     amount:14,scaledBySkill:false,available:true}
   ];
   const calc={
    healingSpells:{rows:skillRows},
    stats:{vit:50,str:70,agi:70,dex:55,spi:80,int:35},
    combat:{incredibleStrength:{applies:true,id:910110001},
     attack:{walkingBase:160},defense:{directRaw:80},
     accuracy:{base:100},dodge:{base:130}},
    periodicRecovery:{rows:[{id:330005001,name:'Wrong autogenerated',
     amount:5,kind:'mp',available:false,required:0}]},
    songSkills:{rows:[{id:340001001,name:'A bad name',
     nameEn:'A bad EN name',description:'Текст источника',
     descriptionEn:'Source description',requirements:[{branch:'hymn',amount:8}],
     available:false}]},
    priestCast:window.PandoraOSCalculator.priestCastPreviews({
     spi:134,blessing:90,hymn:30,skills:terms.skills
    }),
    resistances:{status:{stun:15}},
    procPreview:{entries:[{code:'EP_ONHIT_SKILL_EXEC',
     source:'Тестовый предмет',trigger:'При ударе',triggerEn:'On hit',
     skillId:310004001,skillName:'Лечение',skillNameEn:'Heal',chance:15}]}
   };
   window.PandoraStageAttributes.render(host,{
    page:chapter,modifiers:calc,gameTerms:terms,
    heroJobKey:'ENCHANTER',heroLevel:45,
    heroMasteries:{hymn:8,blessing:78,exorcism:26},
    heroBranchCaps:terms.classes.ENCHANTER.branchCaps,
    skillIconForId:id=>terms.skills[String(id)]?.iconId?
     'assets/skills/icons/skill_'+terms.skills[String(id)].iconId+'.webp':null,
    buffs:{priestEnabled:true,priestSpi:134,priestBlessing:90,priestHymn:30},
    combatSkillCards:{combatLunge:{
     name:terms.skills['100051001'].name,
     nameEn:terms.englishSkills['100051001'].n,
     desc:terms.skills['100051001'].desc,
     descEn:terms.englishSkills['100051001'].d}},
    availability:{combatLunge:true}
   });
   return host.querySelector('.stage-book-page')?.textContent||'';
  },{lang,chapter});
  const ru=await render({lang:'ru',chapter:'effects'});
  for(const name of ['Первая помощь','Массовое исцеление','Песнь поэта','Песнопения'])
   assert.ok(ru.includes(name),'Book effects need OS/Remaked RU '+name+'; seen '+ru.slice(0,600));
  assert.equal(ru.includes('Лечение'),false,'Unavailable Heal is encyclopedic, not a current-build result');
  assert.equal(ru.includes('Природное восстановление'),false,'Unavailable recovery does not enter Book');
  assert.equal(ru.includes('Неверный автоперевод'),false);
  assert.equal(ru.includes('Гимны'),false);
  // Real browser proof: the source-only catalog remains outside the Book, but
  // exact recipient-side bonuses are again calculated for THIS build.
  const party=page.locator('#book-source-qa .stage-skill-party-effects');
  assert.equal(await party.count(),1,'Computed effects from allies must remain visible');
  await party.locator('summary').first().click();
  const partyText=await party.innerText();
  for(const [name,amount] of [['Боевой клич','+42 АТК'],
   ['Массовая сосредоточенность','+35'],['Помощь ветра','+34']])
   assert.ok(partyText.includes(name)&&partyText.includes(amount),
    'Computed beneficiary bonus missing: '+name);
  assert.match(partyText,/не включаются в билд автоматически/);
  const how=party.locator('.stage-skill-party-row .stage-skill-gate-help').first();
  await how.locator('summary').click();
  assert.match(await how.innerText(),/Следующая \+1 при значении/);
  assert.match(await how.innerText(),/165/);
  const nextGroup=page.locator('#book-source-qa .stage-skill-next-mastery');
  assert.equal(await nextGroup.count(),1);
  await nextGroup.locator('summary').click();
  assert.match(await nextGroup.innerText(),/Беспощадный удар/);
  assert.match(await nextGroup.innerText(),/Освоено: 0\/3/);
  for(const name of ['Первая помощь','Храм','Восстановление'])
   assert.ok(ru.includes(name),'Hero Book must use exact current OS skill name '+name);
  assert.ok(!ru.includes('Невероятная сила'),
   'Passive on-hit skills must not occupy the castable Skill Effects inspector');
  // The current Book's 340001001 song magnitude is grouped with the
  // offensive skill inspector, not the unused historical song subchapter.
  // Healing alone starts expanded, so open Offensive for its lazy icon.
  const offense=page.locator('#book-source-qa .stage-attacking-skills');
  assert.equal(await offense.getAttribute('open'),null,
   'Skill Effects start with offensive previews collapsed');
  await offense.locator('summary').click();
  const required=[310001001,310021001,310022001,310023001,340001001];
  // The new collapsed subchapters use lazy-loaded artwork; force each source
  // icon into the scrollport before checking that the original sprite loaded.
  for(const id of required){
   const img=page.locator('#book-source-qa .stage-effect-skill-label img[src$="skill_'+id+'.webp"]').first();
   await img.scrollIntoViewIfNeeded({timeout:12000});
  }
  // Explicitly expanding a chapter is an intentional user action; ask the
  // browser to load its original art rather than waiting on offscreen lazy
  // images after subsequent scroll restoration.
  await page.locator('#book-source-qa .stage-effect-skill-label img')
   .evaluateAll(images=>images.forEach(img=>{img.loading='eager';}));
  await page.waitForFunction(ids=>ids.every(id=>{
   const img=document.querySelector('#book-source-qa .stage-effect-skill-label img[src$="skill_'+id+'.webp"]');
   return img?.complete&&img.naturalWidth>0;
  }),required,{timeout:12000});
  assert.equal(await page.locator('#book-source-qa .stage-effect-skill-label img').count()>=5,true,
   'All five available source skills have their original icon, without a locked Heal');
  const imageBounds=await page.locator('#book-source-qa .stage-effect-skill-label img').evaluateAll(
   images=>images.map(img=>({width:img.getBoundingClientRect().width,
    height:img.getBoundingClientRect().height,src:img.getAttribute('src'),
    border:parseFloat(getComputedStyle(img).borderTopWidth),
    borderColor:getComputedStyle(img).borderTopColor})));
  for(const icon of imageBounds){
   assert.ok(icon.border>=1 && icon.borderColor!=='rgba(0, 0, 0, 0)',
    'Effect icon needs the same visible gold rim as the skill path: '+JSON.stringify(icon));
   assert.ok(Math.abs(icon.width-26)<=1 && Math.abs(icon.height-26)<=1,
    'Original effect icon must remain a compact 26px badge: '+JSON.stringify(icon));
  }
  const scroll=await page.locator('#book-source-qa .stage-healing-spells:not(.stage-attacking-skills):not(.stage-defensive-skills):not(.stage-movement-skills)').evaluate(el=>({
   width:el.getBoundingClientRect().width,scrollWidth:el.scrollWidth}));
  assert.ok(scroll.scrollWidth<=scroll.width+3,
   'Effect icons must not push healing rows beyond the Book: '+JSON.stringify(scroll));
  const en=await render({lang:'en',chapter:'effects'});
  for(const term of ['First Aid','Healing Aura',"Minstrel's Song",'Hymn mastery'])
   assert.ok(en.includes(term),'Book effects need original OS EN '+term+'; seen '+en.slice(0,700));
  assert.equal(en.includes('Mana Restore'),false,'Unavailable MP recovery belongs in Wiki');
  assert.equal(en.includes('Acolyte class'),false,'Locked class hints do not clutter Book');
  assert.equal(en.includes('A bad EN name'),false);

  const buffsRu=await render({lang:'ru',chapter:'buffs'});
  for(const name of ['Знак атаки','Знак защиты','Чары усиления','Рывок']){
   assert.ok(buffsRu.includes(name),'Book buffs must use exact OS skill name: '+name);
  }
  assert.match(buffsRu,/СИЛ \+9 · ПРВ \+9 · ИНТ \+9/,
   'Book support spell preview must use OS-approved priest magnitudes');
  assert.equal(buffsRu.includes('Гимны'),false);
  const buffsEn=await render({lang:'en',chapter:'buffs'});
  for(const name of ['Velox','Lapis Medio','Enchantment','Lunge'])
   assert.ok(buffsEn.includes(name),'Buff English source name: '+name);
  const defenseRu=await render({lang:'ru',chapter:'defense'});
  assert.ok(defenseRu.includes('Оглушение'),'Defense status name retained in Russian');
  assert.ok(defenseRu.includes('15'),'Defense numeric effect is unchanged');
  const defenseEn=await render({lang:'en',chapter:'defense'});
  assert.ok(defenseEn.includes('Stun'),'Defense bilingual label remains independent');
  await render({lang:'ru',chapter:'attack'});
  const procPanel=page.locator('#book-source-qa .stage-source-events');
  assert.equal(await procPanel.count(),1);
  await procPanel.locator('summary').click();
  const triggered=procPanel.locator('[data-source-skill-id="310004001"]');
  assert.equal(await triggered.count(),1,
   'Item/Soul effect names must attach their canonical skill source ID');
  assert.match(await triggered.innerText(),/Лечение/);
  await triggered.hover();
  const rich=page.locator('#path-skill-hover-tooltip');
  // This Book is rebuilt several times in the same isolated scenario.
  // If the delayed hover was interrupted by scroll/sprite layout, recover
  // with a genuine pointer move inside the *same* linked skill.
  if(!await triggered.evaluate(node=>node.matches(':hover')))
   await triggered.hover();
  await page.waitForTimeout(600);
  if(!await rich.isVisible()){
   const bounds=await triggered.boundingBox();
   assert.ok(bounds&&bounds.width>=6,'Skill source hover target must be measurable');
   await page.mouse.move(bounds.x+bounds.width/2-2,bounds.y+bounds.height/2);
   await page.mouse.move(bounds.x+bounds.width/2+2,bounds.y+bounds.height/2);
  }
  await rich.waitFor({state:'visible',timeout:5000});
  assert.match(await rich.locator('strong').first().innerText(),/Лечение/);
  assert.ok(await rich.locator('img').count()>0,
   'Item/Soul triggered skill tooltip must use the real Path icon');
  await procPanel.locator('summary').hover();
  assert.deepEqual(errors,[]);
  console.log('Chromium Book 664: OS/Remaked RU+EN skills, Hymn/Песнопения, Адепт, buffs and defense');
 }finally{await context.close()}
}
